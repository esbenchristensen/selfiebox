"""Selfi logo (marketing/brandpakke/01_logo/svg/selfi-logo-hvid.svg) as OpenSCAD polygons for the gen 2 front inlay.
Usage: python3 hardware/cad/make_logo_scad.py  ->  hardware/cad/logo_selfi.scad
Strokes are outlined (butt caps, as in the SVG); white = mark + letters, green = the two circles (lens dot, dot over the i);
logo_all2d is their union in one outline, for the pocket in the front."""
import re, xml.etree.ElementTree as ET
from pathlib import Path
import numpy as np
from svgpathtools import parse_path
from shapely.geometry import Polygon, LineString, Point, MultiPolygon
from shapely.ops import unary_union

ROOT = Path(__file__).resolve().parents[2]
SVG = ROOT / "marketing/brandpakke/01_logo/svg/selfi-logo-hvid.svg"
OUT = Path(__file__).with_name("logo_selfi.scad")
HEIGHT = 10.0   # mm, the mark's visible height (= the viewBox height)

def mat(t):
    M = np.eye(3)
    for name, args in re.findall(r"(\w+)\(([^)]*)\)", t or ""):
        a = [float(v) for v in re.split(r"[ ,]+", args.strip())]
        if name == "translate": N = np.array([[1, 0, a[0]], [0, 1, a[1] if len(a) > 1 else 0], [0, 0, 1]])
        elif name == "scale": N = np.diag([a[0], a[1] if len(a) > 1 else a[0], 1])
        else: raise ValueError(name)
        M = M @ N
    return M

def pts(seg_path, n=24):
    out = []
    for seg in seg_path:
        k = n if type(seg).__name__ != "Line" else 1
        for t in np.linspace(0, 1, k, endpoint=False): z = seg.point(t); out.append((z.real, z.imag))
    z = seg_path[-1].point(1); out.append((z.real, z.imag))
    return np.array(out)

def tf(M, p): return (np.c_[p, np.ones(len(p))] @ M.T)[:, :2]

ns = "{http://www.w3.org/2000/svg}"
tree = ET.parse(SVG); root = tree.getroot()
H_UNITS = float(root.get("viewBox").split()[3]); W_UNITS = float(root.get("viewBox").split()[2])
white, green = [], []
def walk(el, M):
    M = M @ mat(el.get("transform"))
    tag = el.tag.replace(ns, "")
    if tag == "circle":
        c = tf(M, np.array([[float(el.get("cx")), float(el.get("cy"))]]))[0]; r = float(el.get("r")) * M[0, 0]
        green.append(Point(c).buffer(r, 64))
    elif tag == "path":
        p = parse_path(el.get("d"))
        if el.get("stroke") and el.get("fill") == "none":
            w = float(el.get("stroke-width")) * M[0, 0]
            white.append(LineString(tf(M, pts(p))).buffer(w/2, cap_style="flat", join_style="round", quad_segs=16))
        else:   # filled glyph, non-zero rule: subpaths wound like the largest one add, the others cut
            rings = [tf(M, pts(sub, 12)) for sub in p.continuous_subpaths()]
            area = [0.5*np.sum(r[:-1, 0]*r[1:, 1] - r[1:, 0]*r[:-1, 1]) for r in rings]
            sign = np.sign(max(area, key=abs))
            add = unary_union([Polygon(r).buffer(0) for r, a in zip(rings, area) if np.sign(a) == sign])
            cut = unary_union([Polygon(r).buffer(0) for r, a in zip(rings, area) if np.sign(a) != sign])
            white.append(add.difference(cut))
    for ch in el: walk(ch, M)
walk(root, np.eye(3))
W = unary_union(white)
G = unary_union(green)                          # the circles: the lens dot and the dot over the i
W = W.difference(G)
k = HEIGHT / H_UNITS
def scad(geom, name):
    geoms = list(geom.geoms) if hasattr(geom, "geoms") else [geom]
    out = [f"module {name}() {{"]
    for g in geoms:
        g = g.simplify(0.5)
        rings = [g.exterior] + list(g.interiors)
        P, paths, i = [], [], 0
        for r in rings:
            c = [((x - W_UNITS/2)*k, (H_UNITS/2 - y)*k) for x, y in list(r.coords)[:-1]]
            P += c; paths.append(list(range(i, i + len(c)))); i += len(c)
        out.append("  polygon(points=[" + ",".join(f"[{x:.3f},{y:.3f}]" for x, y in P) + "], paths=" + str(paths) + ");")
    return "\n".join(out + ["}"])
OUT.write_text("// Generated by make_logo_scad.py from the brand pack's white logo: do not edit.\n"
               f"// 2D, centred on the origin, {W_UNITS*k:.1f} x {HEIGHT:.1f} mm, x right, y up.\n"
               f"LOGO_SIZE = [{W_UNITS*k:.2f}, {HEIGHT:.2f}];\n" + scad(W, "logo_white2d") + "\n" + scad(G, "logo_green2d") + "\n"
               + scad(unary_union([W, G]).buffer(0.01).buffer(-0.01), "logo_all2d") + "\n")
print(OUT, "white parts", len(W.geoms) if hasattr(W, "geoms") else 1, "green", len(G.geoms) if hasattr(G, "geoms") else 1)
