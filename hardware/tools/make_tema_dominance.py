#!/usr/bin/env python3
"""The Airtox Dominance theme test kit for gen 2 (Esben 31 Oct 2026): writes hardware/cad/tema_dominance.scad, the 2D shapes
that gen2_concept.scad's dom_top() / dom_wing() extrude.

Esben: the Dominance theme is the main theme test, in every print package from v36 on, and it must hold on the wall (B2B) and
on the floor stand (B2C). Colours: Selfi black (the box's own filament), the logo's orange-red and white, nothing grey. The logo
is the league's own artwork traced in tools/logos/airtox_dominance*.geo.json (venue_themes.py): ask ADFC and Airtox for the
official files and their permission before a box with it leaves the house.

Shapes (mm):
  dom_top_sign()      the topper's outline: half an octagon, 2*DOM_TOP_HW wide (289: fits the H2C plate turned, 292), its
                      base on the box's top face; local x, z from TOP_Z0
  dom_top_white/orange()   the logo's inlays in the same frame (orange = the bar minus the white letters in it)
  dom_wing_white(sx) / dom_wing_orange(sx)   a post's name (reads bottom to top on both sides) and its orange cap, in the
                      box's x, z (sx = -1 left, 1 right)
The posts' outline is drawn in gen2_concept.scad (a rounded rectangle, DOM_POST_W wide).

Usage: python3 hardware/tools/make_tema_dominance.py
Needs: shapely, matplotlib (venue_themes.py)
"""
import sys
from pathlib import Path

from shapely import affinity
from shapely.geometry import MultiPolygon, Polygon, box

sys.path.insert(0, str(Path(__file__).resolve().parent))
import venue_themes as vt  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "cad" / "tema_dominance.scad"
W, H = 224.5, 307.0
XE = W / 2 + 0.2               # a wing's inner face (gen2_concept.scad: theme_wing)
POST_W = 32.0                  # post width: the topper 2 * (XE + POST_W) = 289
TOP_HW, TOP_H, TOP_FLAT = XE + POST_W, 92.0, 82.0
POST_Z = (20.0, 305.0)         # post panel bottom and top (WING_BOT .. under the topper at 307.2)
CAP = 30.0                     # orange cap at the top of a post
EDGE = 3.0                     # no inlay closer than this to a part's edge
SIMPLIFY = 0.02


def polys(g):
    g = g.buffer(0)
    if g.is_empty:
        return []
    return [p for p in (g.geoms if isinstance(g, MultiPolygon) else [g]) if isinstance(p, Polygon) and p.area > 0.05]


def scad_polygon(g):
    """shapely geometry -> one OpenSCAD polygon() per part (holes as extra paths)."""
    out = []
    for p in polys(g.simplify(SIMPLIFY)):
        pts, paths = [], []
        for ring in [p.exterior, *p.interiors]:
            c = list(ring.coords)[:-1]
            paths.append(list(range(len(pts), len(pts) + len(c))))
            pts += c
        P = ",".join(f"[{x:.3f},{y:.3f}]" for x, y in pts)
        Q = ",".join("[" + ",".join(map(str, q)) + "]" for q in paths)
        out.append(f"    polygon(points=[{P}], paths=[{Q}]);")
    return "\n".join(out) if out else "    square(0);"


def top():
    ch = (TOP_HW - TOP_FLAT) * 0.75
    sign = Polygon([(-TOP_HW, 0), (-TOP_HW, TOP_H - ch), (-TOP_FLAT, TOP_H), (TOP_FLAT, TOP_H), (TOP_HW, TOP_H - ch), (TOP_HW, 0)])
    sign = sign.buffer(3, join_style=1).buffer(-3, join_style=1)
    logo = dict(vt.place_logo(vt.traced_logo("airtox_dominance"), (-100, 14, 100, 78), [("orange", "orange"), ("white", "white")]))
    inner = sign.buffer(-EDGE)
    white = logo["white"].intersection(inner)
    orange = logo["orange"].difference(logo["white"].buffer(0.05)).intersection(inner)
    return sign, white, orange


def post(sx):
    x0, x1 = XE, XE + POST_W
    z0, z1 = POST_Z
    outline = box(x0, z0, x1, z1).buffer(-4).buffer(4)
    cap = outline.intersection(box(x0 - 1, z1 - CAP, x1 + 1, z1 + 1)).buffer(-EDGE).buffer(EDGE - 0.01).intersection(outline.buffer(-EDGE))
    word = vt.U(*[g for _, g in vt.place_logo(vt.traced_logo("airtox_dominance_word"), (0, 0, 200, 10), [("white", "white")])])
    word = affinity.rotate(word, 90, origin=(0, 0))                       # reads bottom to top
    word = vt.fit(word, (x0 + 9, z0 + 14, x1 - 9, z1 - CAP - 14))
    if sx < 0:
        cap, word = (affinity.scale(g, -1, 1, origin=(0, 0)) for g in (cap, word))
        word = vt.flip_text(word)                                         # still reads bottom to top
    return word, cap


def main():
    sign, white, orange = top()
    parts = [("dom_top_sign", sign), ("dom_top_white", white), ("dom_top_orange", orange)]
    lines = ["// Generated by hardware/tools/make_tema_dominance.py: do not edit. The Airtox Dominance theme's 2D shapes (mm).",
             f"DOM_POST_W = {POST_W};  DOM_POST_Z = [{POST_Z[0]}, {POST_Z[1]}];  DOM_TOP_HW = {TOP_HW};  DOM_TOP_H = {TOP_H};", ""]
    for name, g in parts:
        lines += [f"module {name}() {{", scad_polygon(g), "}"]
    for side, sx in (("v", -1), ("h", 1)):
        word, cap = post(sx)
        lines += [f"module dom_wing_white_{side}() {{", scad_polygon(word), "}", f"module dom_wing_orange_{side}() {{", scad_polygon(cap), "}"]
    lines += ["module dom_wing_white(sx) if (sx < 0) dom_wing_white_v(); else dom_wing_white_h();",
              "module dom_wing_orange(sx) if (sx < 0) dom_wing_orange_v(); else dom_wing_orange_h();", ""]
    OUT.write_text("\n".join(lines))
    print(OUT, f"top {2 * TOP_HW:.1f} x {TOP_H} mm, white {white.area:.0f} mm2, orange {orange.area:.0f} mm2")


if __name__ == "__main__":
    main()
